/**
 * Build-time script: Generates a JS module with relative path constants or embedded base64.
 * Embedding header/footer/logos as base64 data URLs ensures they are always loaded instantly
 * on the client without network fetches or CORS issues, resolving missing assets in PDF exports.
 */

const fs = require("fs");
const path = require("path");

const OUTPUT_FILE = path.join(__dirname, "..", "src", "utils", "pdfImageAssets.js");
const PUBLIC_DIR = path.join(__dirname, "..", "public");

const IMAGE_FILES = [
  { varName: "COVER_BG", filename: "newBg.jpg", embed: false },
  { varName: "LOGO", filename: "ht-logo.png", embed: true },
  { varName: "HEADER_IMG", filename: "header.png", embed: true },
  { varName: "FOOTER_IMG", filename: "footer.png", embed: true },
  { varName: "CONTACT_PAGE", filename: "proposal-contact.jpg", embed: false },
  { varName: "HT_LOGO", filename: "ht-logo.png", embed: true },
  { varName: "ARTBOARD_1", filename: "Artboard1.jpg", embed: false },
  { varName: "ARTBOARD_2", filename: "Artboard 2.jpg", embed: false },
  { varName: "ARTBOARD_3", filename: "Artboard 3.jpg", embed: false },
  { varName: "ARTBOARD_4", filename: "Artboard 4.jpg", embed: false },
  { varName: "ARTBOARD_5", filename: "Artboard 5.jpg", embed: false },
];

const MIME_MAP = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  gif: "image/gif",
  webp: "image/webp",
  svg: "image/svg+xml",
};

function getBase64DataUrl(filename) {
  const filePath = path.join(PUBLIC_DIR, filename);
  if (!fs.existsSync(filePath)) {
    console.warn(`[generate-base64-images] Warning: File not found at ${filePath}`);
    return `/${filename}`;
  }
  const buffer = fs.readFileSync(filePath);
  const base64 = buffer.toString("base64");
  const ext = path.extname(filename).slice(1).toLowerCase();
  const mimeType = MIME_MAP[ext] || "application/octet-stream";
  return `data:${mimeType};base64,${base64}`;
}

function generateModule() {
  console.log("[generate-base64-images] Generating relative asset paths and base64 embeds...");

  const exports = [];

  for (const { varName, filename, embed } of IMAGE_FILES) {
    if (embed) {
      const dataUrl = getBase64DataUrl(filename);
      exports.push(`export const ${varName} = "${dataUrl}";`);
    } else {
      exports.push(`export const ${varName} = "/${filename}";`);
    }
  }

  const moduleContent = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT MANUALLY
 * Generated by scripts/generate-base64-images.js during build.
 * 
 * Contains relative asset paths or embedded Base64 data URLs for static design assets.
 */

${exports.join("\n")}
`;

  fs.writeFileSync(OUTPUT_FILE, moduleContent, "utf-8");
  console.log(`[generate-base64-images] Done → ${OUTPUT_FILE}`);
}

generateModule();
