/**
 * Build-time script: Generates a JS module with relative path constants.
 * These relative paths are converted to Base64 at PDF generation time
 * using the server-side /api/static-image API.
 */

const fs = require("fs");
const path = require("path");

const OUTPUT_FILE = path.join(__dirname, "..", "src", "utils", "pdfImageAssets.js");

const IMAGE_FILES = [
  { varName: "COVER_BG",        filename: "newBg.png" },
  { varName: "LOGO",            filename: "download.jpg" },
  { varName: "HEADER_IMG",      filename: "header.png" },
  { varName: "FOOTER_IMG",      filename: "footer.png" },
  { varName: "CONTACT_PAGE",    filename: "proposal-contact.png" },
  { varName: "HT_LOGO",         filename: "ht-logo.png" },
  { varName: "ARTBOARD_1",      filename: "Artboard1.jpg" },
  { varName: "ARTBOARD_2",      filename: "Artboard 2.jpg" },
  { varName: "ARTBOARD_3",      filename: "Artboard 3.jpg" },
  { varName: "ARTBOARD_4",      filename: "Artboard 4.jpg" },
  { varName: "ARTBOARD_5",      filename: "Artboard 5.jpg" },
];

function generateModule() {
  console.log("[generate-base64-images] Generating relative asset paths...");

  const exports = [];

  for (const { varName, filename } of IMAGE_FILES) {
    exports.push(`export const ${varName} = "/${filename}";`);
  }

  const moduleContent = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT MANUALLY
 * Generated by scripts/generate-base64-images.js during build.
 * 
 * Contains relative asset paths for all static design assets.
 * These are resolved to Base64 at PDF export time.
 */

${exports.join("\n")}
`;

  fs.writeFileSync(OUTPUT_FILE, moduleContent, "utf-8");
  console.log(`[generate-base64-images] Done → ${OUTPUT_FILE}`);
}

generateModule();
