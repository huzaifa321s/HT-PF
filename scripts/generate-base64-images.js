/**
 * Build-time script: Generates a JS module with remote URL constants
 * pointing to the Express backend.
 * 
 * This resolves image loading issues in @react-pdf/renderer v4.x
 * by loading from the Express backend which allows CORS (*).
 */

const fs = require("fs");
const path = require("path");

const OUTPUT_FILE = path.join(__dirname, "..", "src", "utils", "pdfImageAssets.js");

const IMAGE_FILES = [
  { varName: "COVER_BG",        filename: "newBg.png" },
  { varName: "LOGO",            filename: "download.jpg" },
  { varName: "HEADER_IMG",      filename: "new-header.png" },
  { varName: "FOOTER_IMG",      filename: "footer.png" },
  { varName: "CONTACT_PAGE",    filename: "proposal-contact.png" },
  { varName: "HT_LOGO",         filename: "ht-logo.png" },
];

function generateModule() {
  console.log("[generate-base64-images] Generating remote asset URLs...");

  const exports = [];

  for (const { varName, filename } of IMAGE_FILES) {
    exports.push(`export const ${varName} = \`\${cleanBaseURL}/${filename}\`;`);
  }

  const moduleContent = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT MANUALLY
 * Generated by scripts/generate-base64-images.js during build.
 * 
 * Contains remote asset URLs pointing to the Express backend.
 * This resolves react-pdf/renderer v4 image loading and rendering issues.
 */

const baseURL = process.env.NEXT_PUBLIC_APP_BASE_URL || "http://localhost:5000";
const cleanBaseURL = baseURL.endsWith("/") ? baseURL.slice(0, -1) : baseURL;

${exports.join("\n")}
`;

  fs.writeFileSync(OUTPUT_FILE, moduleContent, "utf-8");
  console.log(`[generate-base64-images] Done → ${OUTPUT_FILE}`);
}

generateModule();
