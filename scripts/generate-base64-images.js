/**
 * Build-time script: Reads public/ images and generates a JS module
 * with base64 data URL constants.
 * 
 * This runs during `npm run build` on Vercel (where the filesystem IS available
 * during build — it's only the serverless functions at runtime that lack it).
 * 
 * The generated module is imported by components so images are part of the JS bundle.
 * This is the ONLY approach that works 100% on Vercel because:
 *   - No CORS issues (images are inline data: URLs)
 *   - No CDN issues (no network requests at all)
 *   - No serverless filesystem issues (generated at build time, not runtime)
 */

const fs = require("fs");
const path = require("path");

const PUBLIC_DIR = path.join(__dirname, "..", "public");
const OUTPUT_FILE = path.join(__dirname, "..", "src", "utils", "pdfImageAssets.js");

const MIME_MAP = {
  png: "image/png",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  gif: "image/gif",
  webp: "image/webp",
  svg: "image/svg+xml",
};

// Images used in the PDF export container
const IMAGE_FILES = [
  { varName: "COVER_BG",        filename: "newBg.png" },
  { varName: "LOGO",            filename: "download.jpg" },
  { varName: "HEADER_IMG",      filename: "new-header.png" },
  { varName: "FOOTER_IMG",      filename: "footer.png" },
  { varName: "CONTACT_PAGE",    filename: "proposal-contact.png" },
  { varName: "HT_LOGO",         filename: "ht-logo.png" },
];

function generateModule() {
  console.log("[generate-base64-images] Starting...");

  const exports = [];

  for (const { varName, filename } of IMAGE_FILES) {
    const filePath = path.join(PUBLIC_DIR, filename);

    if (!fs.existsSync(filePath)) {
      console.warn(`  ⚠ File not found: ${filePath} — skipping`);
      exports.push(`export const ${varName} = "/${filename}"; // fallback: file not found at build time`);
      continue;
    }

    const buffer = fs.readFileSync(filePath);
    const ext = path.extname(filename).slice(1).toLowerCase();
    const mime = MIME_MAP[ext] || "application/octet-stream";
    const base64 = buffer.toString("base64");
    const dataUrl = `data:${mime};base64,${base64}`;

    const sizeKB = (buffer.length / 1024).toFixed(1);
    console.log(`  ✓ ${filename} → ${varName} (${sizeKB} KB)`);

    exports.push(`export const ${varName} = "${dataUrl}";`);
  }

  const moduleContent = `/**
 * AUTO-GENERATED FILE — DO NOT EDIT MANUALLY
 * Generated by scripts/generate-base64-images.js during build.
 * 
 * Contains base64 data URLs for all images used in PDF export.
 * This ensures images render correctly in html2canvas regardless of
 * deployment environment (Vercel, etc.) — no CORS, no CDN, no fetch.
 */

${exports.join("\n\n")}
`;

  fs.writeFileSync(OUTPUT_FILE, moduleContent, "utf-8");
  console.log(`[generate-base64-images] Done → ${OUTPUT_FILE}`);
}

generateModule();
